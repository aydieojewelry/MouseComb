//! Writes the typed TypeScript client for every command and event to
//! `packages/bindings/src/index.ts`. Run after changing a command:
//! `pnpm bindings` (repo root).

use specta_typescript::Typescript;

fn main() {
    let out = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../packages/bindings/src/index.ts");
    // Type collection recurses through nested JSON types; give it room.
    std::thread::Builder::new()
        .stack_size(64 * 1024 * 1024)
        .spawn(move || {
            mousecomb_desktop_lib::specta_builder()
                .export(Typescript::default().header("// Generated by `pnpm bindings`. Do not edit.\n"), out)
                .expect("failed to export TypeScript bindings");
        })
        .expect("spawn export thread")
        .join()
        .expect("export thread panicked");
    println!("wrote {out}");
}
